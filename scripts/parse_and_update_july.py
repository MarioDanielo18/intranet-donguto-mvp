def parse_time_str(time_str):
    parts = time_str.strip().split(':')
    h = int(parts[0])
    m = parts[1]
    ampm = "PM" if h >= 12 else "AM"
    dh = h - 12 if h > 12 else (12 if h == 0 else h)
    formatted_time = f"{dh:02d}:{m} {ampm}"
    iso_time = f"{h:02d}:{m}:00Z"
    return formatted_time, iso_time

